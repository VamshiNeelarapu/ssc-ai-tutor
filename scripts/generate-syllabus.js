// Regenerates lib/ssc-syllabus-data.ts from docs/ssc-breakdown.md (Parts II-III: subjects 4-12).
// Usage: node scripts/generate-syllabus.js
const fs = require("fs");
const path = require("path");

const SRC = path.join(__dirname, "..", "docs", "ssc-breakdown.md");
const OUT = path.join(__dirname, "..", "lib", "ssc-syllabus-data.ts");

const SUBJECT_NAMES = {
  4: "General Intelligence & Reasoning",
  5: "General Awareness",
  6: "Quantitative Aptitude",
  7: "English Comprehension",
  8: "Mathematical Abilities (Tier-II)",
  9: "Reasoning & General Intelligence (Tier-II)",
  10: "English Language & Comprehension (Tier-II)",
  11: "General Awareness (Tier-II)",
  12: "Computer Knowledge Test (CKT)",
};

// Flat subjects have no "## x.y" headings; their checklist goes under one synthetic section.
const FLAT_SECTION_NAMES = {
  8: "Tier-II Mathematical Abilities checklist",
  9: "Tier-II Reasoning checklist",
  10: "Tier-II English checklist",
  11: "Tier-II General Awareness checklist",
};

// Display-name overrides. The slug keeps coming from the original title so existing links stay stable.
const SECTION_RENAMES = { "Current affairs": "Static GK" };

function toSlug(name) {
  return name
    .toLowerCase()
    .replace(/[&]/g, "and")
    .replace(/[^a-z0-9\s-]/g, "")
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");
}

const lines = fs.readFileSync(SRC, "utf8").split(/\r?\n/);
const subjects = [];
let subject = null;
let section = null;
let skipSection = false;

for (const raw of lines) {
  const line = raw.trimEnd();

  const subjectMatch = /^# (\d+)\. (.+)$/.exec(line);
  if (subjectMatch) {
    const num = Number(subjectMatch[1]);
    subject = null;
    section = null;
    skipSection = false;
    if (SUBJECT_NAMES[num]) {
      const name = SUBJECT_NAMES[num];
      subject = { num, name, slug: toSlug(name), nodeType: "subject", children: [] };
      subjects.push(subject);
      if (FLAT_SECTION_NAMES[num]) {
        const secName = FLAT_SECTION_NAMES[num];
        section = {
          name: secName,
          slug: `${subject.slug}--${toSlug(secName)}`,
          nodeType: "section",
          children: [],
        };
        subject.children.push(section);
      }
    }
    continue;
  }
  if (/^# /.test(line)) {
    subject = null;
    section = null;
    continue;
  }
  if (!subject) continue;

  const sectionMatch = /^## \d+\.\d+ (.+)$/.exec(line);
  if (sectionMatch) {
    const title = sectionMatch[1].trim();
    // Practice routines / protocols are process checklists, not syllabus topics.
    skipSection = /practice|routine/i.test(title);
    if (skipSection) {
      section = null;
      continue;
    }
    section = {
      name: SECTION_RENAMES[title] ?? title,
      slug: `${subject.slug}--${toSlug(title)}`,
      nodeType: "section",
      children: [],
    };
    subject.children.push(section);
    continue;
  }

  const scopeMatch = /^\*\*Official scope summary:\*\*\s*(.+)$/.exec(line);
  if (scopeMatch) {
    subject.description = scopeMatch[1].trim();
    continue;
  }

  const itemMatch = /^\s*- \[ \] (.+)$/.exec(line);
  if (itemMatch && section && !skipSection) {
    const n = section.children.length + 1;
    section.children.push({
      name: itemMatch[1].trim(),
      slug: `${section.slug}--t${n}`,
      nodeType: "topic",
    });
  }
}

const cleaned = subjects.map(({ num, ...s }) => ({
  ...s,
  children: s.children.filter((sec) => sec.children.length > 0),
}));

const seen = new Set();
(function check(nodes) {
  for (const n of nodes) {
    if (seen.has(n.slug)) throw new Error(`Duplicate slug: ${n.slug}`);
    seen.add(n.slug);
    if (n.children) check(n.children);
  }
})(cleaned);

const header = `// AUTO-GENERATED by scripts/generate-syllabus.js from docs/ssc-breakdown.md — do not hand-edit.
// Regenerate with: node scripts/generate-syllabus.js
import type { SyllabusItem } from "./syllabus-seed";

export const SSC_SYLLABUS: SyllabusItem[] = `;

fs.writeFileSync(OUT, header + JSON.stringify(cleaned, null, 2) + ";\n");

let sections = 0;
let topics = 0;
for (const s of cleaned) {
  sections += s.children.length;
  for (const sec of s.children) topics += sec.children.length;
}
console.log(`Wrote ${OUT}: ${cleaned.length} subjects, ${sections} sections, ${topics} topics`);
